"""Build arena-lite copies of the 8 REAL T2 games (owner: path-to-glory-3; tests only, nothing here goes in the image).

    python tests/realgames/build.py [git ref with tests/oracles + tests/replays, default origin/t3/candidate]

Each game = Denis's hand-written, replay-checked simulator (tests/oracles/<id>.py: same observations, moves and endings
as the real arena in all 91 rr1 matches) wrapped as an arena `Game`, with the arena's own rules text per variant taken
from the public rr1 replays. Game ids are the REAL ids (battleship, hex, ...), so a bot meets exactly what it would meet
in T3, including mesh/experience and mesh/known lookups by id. tests/sweep.py copies this folder into its arena copy.
"""
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
REF = sys.argv[1] if len(sys.argv) > 1 else "origin/t3/candidate"
GAMES = ["battleship", "bulls_and_cows", "dots_and_boxes", "hex", "mini_chess", "nim", "prisoners_dilemma", "rps"]


def git_show(path):
    return subprocess.run(["git", "show", f"{REF}:{path}"], cwd=ROOT, capture_output=True, text=True, check=True).stdout


rules, cats, names = {}, {}, {}
files = subprocess.run(["git", "ls-tree", "--name-only", REF, "tests/replays/"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.split()
for f in files:
    if not f.endswith(".json"):
        continue
    for g in json.loads(git_show(f)).get("games") or []:
        gid = g.get("game_id")
        if gid in GAMES and g.get("rules"):
            label = (g.get("variant") or {}).get("label")
            rules.setdefault(gid, {}).setdefault(label, g["rules"])
            cats[gid], names[gid] = g.get("category", "think"), g.get("game_name", gid)
(HERE / "_real_rules.json").write_text(json.dumps({"rules": rules, "category": cats, "name": names}, indent=0))
for gid in GAMES:
    (HERE / f"_oracle_{gid}.py").write_text(git_show(f"tests/oracles/{gid}.py"))
    (HERE / f"{gid}.py").write_text(
        f'"""Real T2 game `{gid}` for local tests (generated by tests/realgames/build.py; do not edit)."""\n'
        f"from . import _oracle_{gid} as _o\nfrom ._real import make\n\nRealGame = make({gid!r}, _o)\n")
    print(gid, "variants with rules:", sorted(rules.get(gid, {})))
